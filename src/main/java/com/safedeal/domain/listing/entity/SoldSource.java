package com.safedeal.domain.listing.entity;

/**
 * SOLD로 들어온 경로.
 *
 * <p>구분하는 이유: 되돌리기 규칙과 통계 반영 여부가 다르다. 결제로 팔린 건은 환불 절차로만
 * 풀려야 통계가 어긋나지 않고, 판매자가 버튼으로 누른 건은 실수일 수 있어 24시간 안에는
 * 되돌릴 수 있어야 한다. 통계 원료로는 결제 건만 쓴다 — 그래야 가짜 거래로 시세를 조작할 수 없다.
 */
public enum SoldSource {
    /** 결제 완료 이벤트로 전이. 통계에 반영된다. */
    PAYMENT,
    /** 판매자가 직접 눌러 전이. 통계에 반영하지 않는다(플랫폼 밖 직거래). */
    MANUAL
}
